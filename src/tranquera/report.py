STATUS_ORDER = ["met", "partial", "undetermined", "not_met"]


def _env() -> Environment:
    env = Environment(loader=PackageLoader("tranquera", "templates"), autoescape=select_autoescape(["html"]),
                      trim_blocks=True, lstrip_blocks=True)
    return env


def summary(result: AnalysisResult) -> dict:
    applicable = [c for c in result.controls if c.final != Verdict.EXCLUDED]
    counts = Counter(c.final.value for c in applicable)
    n = len(applicable) or 1
    # Partial counts as half: a common, easy-to-explain maturity convention.
    score = round(100 * (counts["met"] + 0.5 * counts["partial"]) / n)
    themes = []
    for theme in THEMES:
        rs = [c for c in applicable if c.control.theme == theme]
        tc = Counter(c.final.value for c in rs)
        themes.append({"key": theme, "total": len(rs), **{s: tc.get(s, 0) for s in STATUS_ORDER}})
    functions = []
    for fid in nist_catalog().functions:
        rs = [x for x in result.nist if x.function == fid]
        fc = Counter(x.status for x in rs)
        functions.append({"key": fid, "total": len(rs), **{s: fc.get(s, 0) for s in STATUS_ORDER + ["out_of_scope"]}})
    findings = [f for f in result.findings if f.source != "pattern"]
    return {
        "applicable": len(applicable), "excluded": len(result.controls) - len(applicable),
        "counts": {s: counts.get(s, 0) for s in STATUS_ORDER}, "score": score,
        "themes": themes, "functions": functions,
        "findings": len(findings), "high": sum(1 for f in findings if f.severity.value == "high"),
        "by_severity": Counter(f.severity.value for f in findings),
    }


def render_html(result: AnalysisResult, fictional: bool = False) -> str:
    lang = result.lang if result.lang in LABELS else "en"
    nist = nist_catalog()
    return _env().get_template("report.html.j2").render(
        r=result, s=summary(result), L=LABELS[lang], lang=lang, t=lambda k, **kw: t(lang, k, **kw),
        nist=nist, version=__version__, fictional=fictional,
        patterns=[f for f in result.findings if f.source == "pattern"],
        register=[f for f in result.findings if f.source != "pattern"],
    )


REGISTER_COLUMNS = ["id", "severity", "source", "root_cause", "title", "detail", "controls", "documents",
                    "action", "action_text", "owner", "due", "status"]


def register_rows(result: AnalysisResult) -> list[dict]:
    lang = result.lang
    rows = []
    for f in result.findings:
        rows.append({
            "id": f.id, "severity": t(lang, f.severity.value), "source": t(lang, f"src_{f.source}"),
            "root_cause": t(lang, f"rc_{f.root_cause}"), "title": f.title, "detail": f.detail,
            "controls": " ".join(f.controls), "documents": " ".join(f.documents),
            "action": t(lang, f.action.value), "action_text": f.action_text,
            "owner": f.owner or t(lang, "unassigned"), "due": f.due.isoformat() if f.due else "",
            "status": t(lang, f.status),
        })
    return rows


def _csv(rows: list[dict], columns: list[str]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=columns, extrasaction="ignore")
    writer.writeheader()
    writer.writerows(rows)
    return buf.getvalue()


def render_register_csv(result: AnalysisResult) -> str:
    return _csv(register_rows(result), REGISTER_COLUMNS)


def render_soa_csv(result: AnalysisResult) -> str:
    lang = result.lang
    rows = [{
        "control": c.control.id, "title": c.control.title(lang), "theme": t(lang, c.control.theme),
        "applicable": "no" if c.final == Verdict.EXCLUDED else "yes",
        "justification": c.exclusion_reason, "status": t(lang, c.final.value),
        "nist_csf": " ".join(c.control.nist),
    } for c in result.controls]
    return _csv(rows, ["control", "title", "theme", "applicable", "justification", "status", "nist_csf"])


def render_json(result: AnalysisResult) -> str:
    data = result.to_dict()
    data["summary"] = {k: v for k, v in summary(result).items() if k != "by_severity"}
    data["tool"] = {"name": "tranquera", "version": __version__}
    return json.dumps(data, ensure_ascii=False, indent=2, default=str)


def write_reports(result: AnalysisResult, out_dir: str | Path, fictional: bool = False) -> dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "html": (out / "report.html", render_html(result, fictional)),
        "register": (out / "findings-register.csv", render_register_csv(result)),
        "soa": (out / "statement-of-applicability.csv", render_soa_csv(result)),
        "json": (out / "results.json", render_json(result)),
    }
    for path, content in files.values():
        # utf-8-sig so the CSVs open with the right accents in Excel
        path.write_text(content, encoding="utf-8-sig" if path.suffix == ".csv" else "utf-8")
    return {k: v[0] for k, v in files.items()}
